#!/usr/bin/env node
// ONTOLOGY VALIDATOR (Steve 2026-10-05)
// Validates that every system file documents itself via @ontology headers,
// and that the documentation matches the actual code.
// Release is BLOCKED if validation fails.

const fs = require('fs');
const path = require('path');

const SRC_DIR = path.join(__dirname, '..', 'src', 'js');
const ERRORS = [];

function parseOntologyHeader(content, filename) {
  const lines = content.split('\n');
  let inBlock = false;
  const header = { system: null, description: null, provides: [], rules: [], consumes: [] };
  let currentSection = null;

  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed === '// @ontology') { inBlock = true; continue; }
    if (!inBlock) continue;
    if (!trimmed.startsWith('//')) break; // end of header block

    const content = trimmed.slice(2).trim();
    if (content.startsWith('system:')) {
      header.system = content.slice(7).trim();
      currentSection = null;
    } else if (content.startsWith('description:')) {
      header.description = content.slice(12).trim();
      currentSection = null;
    } else if (content === 'provides:') {
      currentSection = 'provides';
    } else if (content === 'rules:') {
      currentSection = 'rules';
    } else if (content === 'consumes:') {
      currentSection = 'consumes';
    } else if (content.startsWith('- ') && currentSection) {
      header[currentSection].push(content.slice(2).trim());
    }
  }

  return inBlock ? header : null;
}

function validateFile(filepath) {
  const filename = path.basename(filepath);
  const content = fs.readFileSync(filepath, 'utf8');
  const header = parseOntologyHeader(content, filename);

  if (!header) {
    ERRORS.push(`${filename}: MISSING @ontology header block`);
    return null;
  }

  if (!header.system) ERRORS.push(`${filename}: @ontology missing 'system:'`);
  if (!header.description) ERRORS.push(`${filename}: @ontology missing 'description:'`);

  // Validate provides: each function must exist in the file
  // (as a definition, method, or Game property — not just a bare function)
  for (const prov of header.provides) {
    // Extract function name (before parens or arrow, keep dots for window.X)
    let fnName = prov.split('(')[0].split(' ')[0].split('->')[0].trim();
    // For dotted names like window.BUILD_VERSION, check the last part
    const parts = fnName.split('.');
    fnName = parts[parts.length - 1].replace(/[^a-zA-Z0-9_]/g, '');
    if (!fnName || fnName.length < 2) continue; // skip non-function entries like "state"
    // Check for definition patterns (generous — methods, properties, assignments)
    const patterns = [
      new RegExp(`function\\s+${fnName}\\b`),
      new RegExp(`${fnName}\\s*:\\s*function`),
      new RegExp(`${fnName}\\s*=\\s*function`),
      new RegExp(`\\bG\\.${fnName}\\b`),
      new RegExp(`\\b${fnName}\\s*\\(`),
      new RegExp(`\\b${fnName}\\b\\s*=`),
      new RegExp(`['"]${fnName}['"]\\s*:`),
    ];
    const found = patterns.some(p => p.test(content));
    if (!found) {
      ERRORS.push(`${filename}: provides '${prov}' — '${fnName}' not found in code`);
    }
  }

  // Validate rules: each must cite code location (skip placeholder)
  for (const rule of header.rules) {
    if (rule === '(none documented)') continue;
    if (!rule.includes('(code:')) {
      ERRORS.push(`${filename}: rule '${rule}' — missing (code:) citation`);
    }
  }

  return header;
}

function main() {
  const files = fs.readdirSync(SRC_DIR).filter(f => f.endsWith('.js'));
  const systems = [];

  console.log(`Validating ${files.length} system files...\n`);

  for (const file of files) {
    const filepath = path.join(SRC_DIR, file);
    const header = validateFile(filepath);
    if (header && header.system) {
      systems.push({ file, ...header });
    }
  }

  // Generate the systems table for ONTOLOGY.md
  const ontologyPath = path.join(__dirname, '..', 'docs', 'ONTOLOGY.md');
  if (fs.existsSync(ontologyPath) && ERRORS.length === 0) {
    let doc = fs.readFileSync(ontologyPath, 'utf8');
    const marker = '<!-- Generated by validate-ontology.js — do not edit manually -->';
    const idx = doc.indexOf(marker);
    if (idx !== -1) {
      const table = systems.map(s =>
        `### ${s.system} (\`${s.file}\`)\n${s.description}\n\n` +
        `**Provides:** ${s.provides.length ? s.provides.join(', ') : '—'}\n\n` +
        `**Rules:**\n${s.rules.length ? s.rules.map(r => `- ${r}`).join('\n') : '—'}\n\n` +
        `**Consumes:** ${s.consumes.length ? s.consumes.join(', ') : '—'}\n`
      ).join('\n');
      doc = doc.slice(0, idx + marker.length) + '\n\n' + table + '\n';
      fs.writeFileSync(ontologyPath, doc);
      console.log('Updated docs/ONTOLOGY.md with validated systems\n');
    }
  }

  if (ERRORS.length > 0) {
    console.error('ONTOLOGY VALIDATION FAILED:\n');
    ERRORS.forEach(e => console.error(`  ✗ ${e}`));
    console.error(`\n${ERRORS.length} error(s). Release blocked.`);
    process.exit(1);
  }

  console.log(`✓ All ${systems.length} systems validated`);
  console.log('Ontology matches code. Release permitted.');
}

main();
